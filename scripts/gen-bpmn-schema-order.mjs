// Generates src/bpmn-schema-order.js: the order of child elements the BPMN 2.0 XSD (the copy in
// bpmn-moddle, node_modules/bpmn-moddle/resources/bpmn/xsd) prescribes for every complex type, which the
// minimal-diff writer places new children by and checks every write against (see src/minimal-diff.js,
// schemaRank). Run `node scripts/gen-bpmn-schema-order.mjs` after updating bpmn-js; a unit test fails
// when the committed table differs from what this script generates.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '../src/minimal-diff.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const XSD_DIR = join(root, 'node_modules', 'bpmn-moddle', 'resources', 'bpmn', 'xsd');
const XS = 'http://www.w3.org/2001/XMLSchema';
const PREFIXES = {
  'http://www.omg.org/spec/BPMN/20100524/MODEL': 'bpmn',
  'http://www.omg.org/spec/BPMN/20100524/DI': 'bpmndi',
  'http://www.omg.org/spec/DD/20100524/DI': 'di',
  'http://www.omg.org/spec/DD/20100524/DC': 'dc',
};
const FILES = ['BPMN20.xsd', 'Semantic.xsd', 'BPMNDI.xsd', 'DI.xsd', 'DC.xsd'];

const kids = (el) => el.children.filter((c) => c.kind === 'element');
const attr = (el, name) => el.attrs.find((a) => a.uri === null && a.local === name)?.value ?? null;
const isXs = (el, local) => el.uri === XS && el.local === local;

/** Generates the module's text. */
export function generate(dir = XSD_DIR) {
  const elements = {}; // global element -> type
  const groups = {}; // substitution group head -> direct members
  const types = {}; // type -> { base, own: [element names] }
  for (const file of FILES) {
    const doc = parse(readFileSync(join(dir, file), 'utf8').replace(/^﻿/, ''));
    const schema = doc.root;
    const tns = attr(schema, 'targetNamespace');
    // A QName in an attribute value, resolved where it is written.
    const qname = (el, value) => {
      const [p, l] = value.includes(':') ? value.split(':') : ['', value];
      for (let e = el; e; e = e.parent) {
        if (p in e.nsDecls) return `${PREFIXES[e.nsDecls[p]] ?? `{${e.nsDecls[p]}}`}:${l}`;
      }
      throw new Error(`${file}: unbound prefix in ${value}`);
    };
    const own = `${PREFIXES[tns]}:`;
    const particles = (el, into) => {
      for (const c of kids(el)) {
        if (isXs(c, 'sequence') || isXs(c, 'choice')) particles(c, into);
        else if (isXs(c, 'element')) into.push(attr(c, 'ref') ? qname(c, attr(c, 'ref')) : own + attr(c, 'name'));
        else if (isXs(c, 'any') || isXs(c, 'attribute') || isXs(c, 'anyAttribute')) continue;
        else throw new Error(`${file}: unexpected xsd:${c.local} in a content model`);
      }
      return into;
    };
    for (const c of kids(schema)) {
      if (isXs(c, 'element')) {
        const name = own + attr(c, 'name');
        if (attr(c, 'type')) elements[name] = qname(c, attr(c, 'type'));
        const head = attr(c, 'substitutionGroup');
        if (head) (groups[qname(c, head)] ??= []).push(name);
      } else if (isXs(c, 'complexType')) {
        const name = own + attr(c, 'name');
        const content = kids(c).find((k) => isXs(k, 'complexContent'));
        const ext = content && kids(content).find((k) => isXs(k, 'extension') || isXs(k, 'restriction'));
        if (ext && isXs(ext, 'restriction')) throw new Error(`${file}: ${name} is a restriction`);
        types[name] = { base: ext ? qname(ext, attr(ext, 'base')) : null, own: particles(ext ?? c, []) };
      }
    }
  }
  const sequences = {};
  const sequenceOf = (type) => {
    if (sequences[type]) return sequences[type];
    const t = types[type];
    if (!t) return [];
    const all = [...(t.base ? sequenceOf(t.base) : []), ...t.own];
    if (new Set(all).size !== all.length) throw new Error(`${type}: an element twice in its sequence`);
    return (sequences[type] = all);
  };
  for (const type of Object.keys(types).sort()) sequenceOf(type);
  for (const type of Object.keys(sequences)) if (!sequences[type].length) delete sequences[type];
  const sorted = (obj) => Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]));
  const lines = (obj) => Object.entries(sorted(obj)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  const used = Object.fromEntries(Object.entries(elements).filter(([, type]) => sequences[type]));
  return `// Generated by scripts/gen-bpmn-schema-order.mjs from the BPMN 2.0 XSD in bpmn-moddle. Do not edit.
// The order of child elements the schema prescribes (see src/minimal-diff.js, schemaRank).

/** Namespace URIs of the prefixes below. */
export const NAMESPACES = ${JSON.stringify(Object.fromEntries(Object.entries(PREFIXES).map(([u, p]) => [p, u])), null, 2)};

/** Global elements with element content -> their type. */
export const ELEMENTS = {
${lines(used)}
};

/** Substitution group head -> the elements that may stand for it (directly). */
export const GROUPS = {
${lines(Object.fromEntries(Object.entries(groups).map(([h, m]) => [h, [...m].sort()])))}
};

/** Type -> the elements of its content model in order (inherited ones first; a group head stands for its members). */
export const SEQUENCES = {
${lines(sequences)}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, 'src', 'bpmn-schema-order.js');
  writeFileSync(target, generate());
  console.log(`wrote ${target}`);
}
